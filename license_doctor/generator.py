TEMPLATES: Dict[str, str] = {
    "MIT": MIT_TEMPLATE,
    "Apache-2.0": APACHE_TEMPLATE,
    "BSD-2-Clause": BSD_2_TEMPLATE,
    "BSD-3-Clause": BSD_3_TEMPLATE,
    "ISC": ISC_TEMPLATE,
    "Unlicense": UNLICENSE_TEMPLATE,
}


def list_available_templates() -> List[str]:
    """Return list of supported standard license template IDs."""
    return sorted(TEMPLATES.keys())


def generate_license(
    license_id: str,
    holder: Optional[str] = None,
    year: Optional[int | str] = None,
) -> str:
    """Generate complete license text for the given license identifier."""
    # Lookup case-insensitively
    key = next((k for k in TEMPLATES if k.lower() == license_id.lower()), None)
    if not key:
        available = ", ".join(list_available_templates())
        raise ValueError(f"Unknown license template '{license_id}'. Available templates: {available}")

    current_year = str(year or datetime.datetime.now().year)
    license_holder = holder.strip() if holder else "Copyright Holder"

    template = TEMPLATES[key]
    return template.format(year=current_year, holder=license_holder).strip() + "\n"
